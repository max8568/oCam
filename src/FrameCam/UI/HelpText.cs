namespace FrameCam.UI;

/// <summary>
/// The manual's text (spec 8.4), written for colleagues who are not engineers. A line starting with "# " is a
/// heading, one starting with "- " a bullet point, any other line a paragraph.
/// </summary>
internal static class HelpText
{
    public static IReadOnlyList<HelpBlock> Blocks { get; } = Parse("""
        # 控制列
        控制列是螢幕上那條白色長條。按鈕由左到右是：
        - 錄影：開始錄影。錄影中變成紅色的停止鈕，上面顯示已經錄了多久。
        - 截圖：把錄影框裡的畫面存成一張圖。
        - 常用尺寸：把錄影框改成選單裡的尺寸。
        - 選視窗：點一個視窗，錄影框就對齊那個視窗。
        - 開啟存檔資料夾：打開影片和截圖存放的資料夾。
        - 設定：改存檔資料夾、快捷鍵、每秒格數，以及影片裡要不要有滑鼠游標。
        - 操作說明：打開這份說明。
        - X：結束 FrameCam。錄影中按的話，會先停止錄影、存好檔再結束。
        滑鼠停在按鈕上半秒，會顯示按鈕的名稱，有快捷鍵的也會一起顯示。
        按住最左邊的點點，或長條上沒有按鈕的地方，可以把控制列拖到別的位置。下次打開時，控制列會出現在同一個地方。
        控制列下方有時會出現一個小框，寫著存好的檔名或出問題的原因。

        # 錄影
        - 按控制列的「錄影」或錄影快捷鍵（預設是 F2）開始，再按一次停止。錄影鈕上會寫目前用的快捷鍵。
        - 錄影框框住的地方，就是錄進去的範圍。錄影框的線畫在範圍外面，不會被錄進去。
        - 錄影框、控制列和放大鏡不會出現在影片和截圖裡。錄影中打開設定視窗或這份說明的話，它們會被錄進去。
        - 錄影中錄影框是紅色的，不能拖動，方向鍵也沒有作用；「常用尺寸」和「選視窗」暫時不能按。
        - 會錄進電腦播放的聲音，也就是喇叭或耳機聽到的聲音，不會錄麥克風。找不到播放裝置時只錄畫面，控制列會提醒。
        - 滑鼠游標會錄進影片裡。不想錄到游標的話，在設定裡勾「隱藏滑鼠游標」。
        - 影片存成 MP4，每秒最多 60 格，可以在設定裡改成 30。

        # 截圖
        - 按控制列的「截圖」或截圖快捷鍵（預設是 F3），把錄影框裡的畫面存成 PNG 圖檔。錄影中也可以截圖。
        - 截圖裡沒有滑鼠游標。
        - 存好後，控制列下方會顯示檔名 2 秒。

        # 調整錄影框
        - 拖錄影框的角，可以同時改寬和高；拖一條邊的任何地方，只改那一邊。
        - 要移動整個框，拖左上角外面寫著寬高的標籤（例如「1280 × 720」），或拖框正中央的十字箭頭。框的寬或高小於 96 像素時，不會顯示十字箭頭。
        - 寬和高一定是偶數，拖邊或拖角時一次變 2 像素。MP4 影片的寬和高必須是偶數，這樣錄出來的大小才會跟框一樣。
        - 錄影框最小是 32 × 32，不能超出所在的螢幕，可以蓋住工作列。
        - 錄影框裡面可以直接操作底下的程式。只有正中央的十字箭頭和左上角的寬高標籤那一小塊點不到底下的程式。

        # 放大鏡
        - 拖角、拖邊、拖寬高標籤，或按方向鍵微調時，游標旁邊會出現放大鏡，把正在調整的那個點附近放大，看得到每一個像素。
        - 範圍外的像素會變暗，看得出框的邊停在哪一個像素上。
        - 放大鏡下方寫著寬高和框左上角的座標。座標以主螢幕的左上角為 (0, 0)。
        - 放開滑鼠或停止按鍵 1.5 秒後，放大鏡會消失。用正中央的十字箭頭拖動時，不會出現放大鏡。

        # 用方向鍵微調
        先點一下控制列或錄影框，方向鍵才會作用在錄影框上，不會影響其他程式。
        - 方向鍵：整個框移動 1 像素。
        - Ctrl + 方向鍵：移動最後一次拖過的那條邊或那個角，一次 2 像素。還沒拖過任何邊或角時，移動的是右下角。
        - 最後拖的是左邊或右邊時，只有左右鍵有作用；是上邊或下邊時，只有上下鍵有作用。

        # 自動對齊視窗邊緣
        - 拖邊或拖角時，被拖的邊靠近其他視窗的邊緣（8 像素以內）就會自動貼上去。視窗的外框和視窗內容的邊緣都可以貼。
        - 拖的時候按住 Alt，就不會自動貼上去。

        # 常用尺寸和自訂尺寸
        - 按控制列的「常用尺寸」，選單裡有 1920 × 1080、1280 × 720、854 × 480、640 × 360 和「整個螢幕」。
        - 選了之後，錄影框的左上角不動，大小改成選的尺寸；放不下的話，框會往左上移到放得下為止。比螢幕還大的尺寸是灰色的，不能選。
        - 選單最下面的「新增或刪除自訂尺寸…」可以存自己常用的尺寸。存好的尺寸會出現在選單的「整個螢幕」下面。
        - 在自訂尺寸視窗裡填標籤、寬、高，再按「新增」或 Enter。寬和高一開始填的是目前錄影框的大小，直接按「新增」就是把現在的大小存起來。
        - 標籤可以不填。寬和高要是 32 到 8192 之間的偶數。最多存 20 個尺寸。
        - 要刪掉一個尺寸，按那一行最右邊的 X，或選那一行再按 Delete。

        # 選視窗
        - 按控制列的「選視窗」或選視窗快捷鍵（預設是 F6）。游標移到哪個視窗上，那個視窗就會被框起來，點一下，錄影框就變成那個視窗的範圍。
        - 按住 Ctrl 時，框起來的是游標底下最小的那一塊，例如瀏覽器的網頁區、檔案總管的檔案清單。有些程式（例如 LINE）裡面沒有可以分開選的區塊，只能選整個視窗。
        - 視窗有一部分在螢幕外時，只取螢幕裡面的部分。
        - 按 Esc 取消。錄影中不能選視窗。

        # 設定
        按控制列的「設定」可以改這些項目，改完按「確定」才會存：
        - 存檔資料夾：影片和截圖存在哪裡。
        - 錄影、截圖、選視窗的快捷鍵：點一下欄位，再按想用的按鍵。
        - 每秒格數：30 或 60。
        - 隱藏滑鼠游標：勾起來的話，影片裡不會有滑鼠游標。錄影中才改的話，下一次錄影才會照新的設定。
        快捷鍵如果已經被其他程式用掉，那一格會顯示紅框，換一個按鍵就好。在換好之前，控制列上的按鈕一樣可以用。

        # 檔案存在哪裡
        - 影片和截圖預設存在「影片\FrameCam」資料夾，可以在設定裡改。按控制列的「開啟存檔資料夾」可以直接打開這個資料夾。
        - 檔名是錄影或截圖的時間，例如 2026-10-14_15-30-05.mp4。同一秒有兩個檔案時，後面會加 _2、_3。
        - 設定存在 FrameCam.exe 旁邊的 settings.json，裡面有快捷鍵、自訂尺寸，以及錄影框和控制列上次的位置。

        # 多個螢幕
        - 錄影框只能在一個螢幕裡，不能橫跨兩個螢幕。
        - 把整個框拖到另一個螢幕時，以游標所在的螢幕為準；框比那個螢幕大的話，會自動縮小到放得下。
        - 錄影中拔掉螢幕，或改了螢幕的縮放比例，FrameCam 會先停止錄影並存檔。

        # 出問題的時候
        - 控制列下方的小框會寫出原因，例如快捷鍵登記失敗、存檔資料夾不能寫入。
        - 存檔資料夾不存在時會自動建立；建立不了或不能寫入時，不會開始錄影或截圖。
        - 錄到一半失敗（例如磁碟滿了）時，錄影框會變回藍色，已經錄到的部分會留著。
        - FrameCam.exe 放在不能寫入的資料夾（例如 C:\Program Files）時，設定存不起來，控制列會顯示「設定存檔失敗」。

        # 已知限制
        - 不能錄麥克風、不能暫停、不能存成 GIF。
        - 全螢幕獨佔的遊戲錄不到，視窗模式的遊戲可以錄。
        - 影片每秒的格數不固定：畫面沒有變化時，存進去的格數會比較少，這樣聲音和畫面才對得上。少數剪輯軟體讀這種影片會有問題。
        - 畫面沒有變化時按停止，最後大約 1 秒的畫面和聲音可能沒錄進去。畫面有在動的時候不會。

        # 分享給同事
        - 把整個 FrameCam 資料夾壓縮成 zip 給對方，不能只給 FrameCam.exe。
        - 資料夾裡的 settings.json 會把你的快捷鍵和自訂尺寸一起給對方；不想給的話，壓縮前先刪掉它。
        - 對方的電腦要是 64 位元的 Windows 10（2004 版以後）或 Windows 11，還要裝「Visual C++ 可轉散發套件 x64」。
        - 解壓縮後的資料夾要放在可以寫入的地方，例如桌面或 D 槽。
        - 第一次打開時，Windows 可能顯示「Windows 已保護您的電腦」，按「其他資訊」再按「仍要執行」就可以。
        """);

    private static IReadOnlyList<HelpBlock> Parse(string text) =>
        text.Split('\n')
            .Select(line => line.Trim())
            .Where(line => line.Length > 0)
            .Select(line =>
                line.StartsWith("# ") ? new HelpBlock(HelpKind.Heading, line[2..])
                : line.StartsWith("- ") ? new HelpBlock(HelpKind.Bullet, line[2..])
                : new HelpBlock(HelpKind.Paragraph, line))
            .ToList();
}
